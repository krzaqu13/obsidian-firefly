import esbuild from 'esbuild';
import process from 'process';
import { copy } from "esbuild-plugin-copy";
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/krzaqu13/firefly-plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [
		{
			name: 'sync-to-vault',
			setup(build) {
				build.onEnd(async () => {
					const fs = await import('node:fs');
					const vaultDir = "C:\\Users\\krzza\\Obsidian-vaults\\Kopie zapasowe\\Kopia nr 9\\.obsidian\\plugins\\firefly";
					try {
						// Utrzymuj styles.css w root w synchronizacji z src/styles.css
						if (fs.existsSync("src/styles.css")) {
							fs.copyFileSync("src/styles.css", "styles.css");
						}
						fs.copyFileSync("main.js", `${vaultDir}\\main.js`);
						fs.copyFileSync("manifest.json", `${vaultDir}\\manifest.json`);
						fs.copyFileSync("styles.css", `${vaultDir}\\styles.css`);
						console.log("[esbuild] Synced main.js, manifest.json, styles.css to vault!");
					} catch (e) {
						console.error("[esbuild] Failed to sync to vault:", e);
					}
				});
			},
		},
	],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
